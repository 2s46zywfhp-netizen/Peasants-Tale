interface Look {
  head: keyof typeof HEADS;
  body: string;
  belt: string;
  hands?: string;
  hose?: string;
  robe?: boolean;
  /** Pixels drawn on top (staff, ledger, sword...). */
  prop?: Rows;
  stoop?: boolean;
}

function frame(look: Look, legs: number, blink: boolean): string[] {
  const head = blink ? recolor(HEADS[look.head], { 0: 'e' }) : [...HEADS[look.head]];
  const torso = TORSO.map((r) => r.replace(/B/g, look.body).replace(/L/g, look.belt).replace(/H/g, look.hands ?? 'e'));
  const lower = look.robe
    ? HEM[legs]!.map((r) => r.replace(/B/g, look.body))
    : LEGS[legs]!.map((r) => r.replace(/S/g, look.hose ?? '7'));
  let rows = stack(head, torso, lower);
  if (look.stoop) rows = shiftRows(rows, 0, 7, 1);
  if (look.prop) rows = overlay(rows, look.prop);
  return rows;
}

/** idle: [still, blink]; walk: two strides. */
function person(look: Look): { idle: string[][]; walk: string[][] } {
  return { idle: [frame(look, 0, false), frame(look, 0, true)], walk: [frame(look, 1, false), frame(look, 2, false)] };
}

