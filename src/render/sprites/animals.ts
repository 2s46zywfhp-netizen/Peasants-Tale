import { blank, px, stack, type Rows } from './lib';

const pad = (rows: Rows) => stack(blank(16, 16 - rows.length), rows);

const HEN = px(`
.........8......
........550f....
..5....5559.....
..555555555.....
...5555555......
....55555.......
.....f..f.......
.....f..ff......`);
const HEN_PECK = px(`
................
................
..5.............
..55555555......
...555555550f...
....5555559.....
.....f..f.......
.....ff.f.......`);
const HEN_STEP = px(`
.........8......
........550f....
..5....5559.....
..555555555.....
...5555555......
....55555.......
....f....f......
....ff...f......`);

const PIG = px(`
..........cc....
...eeeeeeeeec...
..eeeeeeeeeeee..
.ceeeeeeeeee0ee.
..eeeeeeeeeeeeaa
..eeeeeeeeeeee..
...eeeeeeeeee...
...ee.ee..ee.ee.
...ee.ee..ee.ee.
...00.00..00.00.`);
const PIG_STEP = [...PIG.slice(0, 7), '..ee..ee.ee..ee.', '..ee..ee.ee..ee.', '..00..00.00..00.'];
const PIG_SNORT = [...PIG.slice(0, 4), '..eeeeeeeeeeee.a', ...PIG.slice(5)];

const COW = px(`
...........6..6.
...........5555.
...........5055.
.5555bb5555555e.
5555bbb555555ee.
b555bb5555bb55..
.5555555bbb55...
.55555555555....
.55.55...55.55..
.55.55...55.55..
.00.00...00.00..`);
const COW_STEP = [...COW.slice(0, 8), '.55..55.55..55..', '.55..55.55..55..', '.00..00.00..00..'];
const COW_TAIL = [...COW.slice(0, 4), '5555bbb555555ee.', '.b55bb5555bb55..', 'b.555555bbb55...', ...COW.slice(7)];

const recolorOx = (rows: Rows) => rows.map((r) => r.replace(/5/g, 'c').replace(/6/g, '5'));
const OX = recolorOx(['..........5....5', ...COW.slice(1)]);

const DOG = px(`
...........0.0..
..........0000..
0.........09000.
.0000000000000..
.000000000000...
.00.0.....0.00..
.00.0.....0.00..`);
const DOG_STEP = [...DOG.slice(0, 5), '..00.0...0..00..', '..00.0...0..00..'];
const DOG_STARE = [...DOG.slice(0, 2), '0.........99000.', ...DOG.slice(3)];

export const ANIMALS = {
  hen: { idle: [pad(HEN), pad(HEN_PECK)], walk: [pad(HEN), pad(HEN_STEP)] },
  pig: { idle: [pad(PIG), pad(PIG_SNORT)], walk: [pad(PIG), pad(PIG_STEP)] },
  cow: { idle: [pad(COW), pad(COW_TAIL)], walk: [pad(COW), pad(COW_STEP)] },
  ox: { idle: [pad(OX), pad(recolorOx(['..........5....5', ...COW_TAIL.slice(1)]))], walk: [pad(OX), pad(recolorOx(['..........5....5', ...COW_STEP.slice(1)]))] },
  blackDog: { idle: [pad(DOG), pad(DOG_STARE)], walk: [pad(DOG), pad(DOG_STEP)] },
} as const;

export type AnimalId = keyof typeof ANIMALS;
