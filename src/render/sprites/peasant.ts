export type PeasantAnim = keyof typeof PEASANT_ANIMS;
export const BODY_VARIANTS = ['stout', 'healthy', 'thin', 'gaunt', 'skeletal', 'sick', 'cold'] as const;
export type BodyVariant = (typeof BODY_VARIANTS)[number];

const TORSO = [7, 13] as const;

/** Body-state variants are transformations of the healthy frames. */
export function bodyVariant(rows: Rows, v: BodyVariant, anim: PeasantAnim): string[] {
  if (anim === 'sleep') {
    // Lying down: show the state in the face only.
    if (v === 'gaunt' || v === 'skeletal') return recolor(rows, { e: v === 'skeletal' ? '5' : '7' }, 10, 12);
    if (v === 'sick') return recolor(rows, { e: 'd' });
    if (v === 'cold') return recolor(rows, { e: '6' });
    return [...rows];
  }
  switch (v) {
    case 'healthy':
      return [...rows];
    case 'stout':
      return girth(girth(rows, 3, 6, 0), TORSO[0] + 1, TORSO[1], 1);
    case 'thin':
      // The belt hangs a row lower on a thinner frame: "your belt is looser".
      return girth(rows, TORSO[0], TORSO[1], -1);
    case 'gaunt':
      return recolor(girth(rows, TORSO[0], TORSO[1], -1), { e: '7' }, 4, 5);
    case 'skeletal':
      return recolor(recolor(girth(girth(rows, TORSO[0], TORSO[1], -2), 13, 15, 0), { e: '5' }, 0, 7), { e: '5', 7: '6' }, 7, 16);
    case 'sick':
      return recolor(rows, { e: 'd', 0: '8' }, 0, 7);
    case 'cold': {
      // Hunched: the head sinks into the shoulders, skin goes blue.
      const hunched = shiftRows(rows, 0, 7, 1);
      return recolor(hunched, { e: '6' });
    }
  }
}
